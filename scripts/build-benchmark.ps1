    $episode = $episodes[$episodeIndex]
    $scenario = 'CONTEXT-{0:D2}' -f ($episodeIndex + 1)
    for ($turnIndex = 0; $turnIndex -lt 2; $turnIndex++) {
        $records.Add([ordered]@{
            id = "$scenario-T$($turnIndex + 1)"
            text = $episode[$turnIndex]
            semanticFamilyId = "BENCHMARK:${scenario}:T$($turnIndex + 1)"
            requiredPolicy = $episode[$turnIndex + 2]
